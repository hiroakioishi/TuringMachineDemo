export const rowsToRules = (rows) =>
  rows.map(([state, read, write, move, next]) => ({ state, read, write, move, next }));

export const rulesToRows = (rules) => rules.map((r) => [r.state, r.read, r.write, r.move, r.next]);

export const PRESETS = raw.map((p) => ({ ...p, rules: rowsToRules(p.rules) }));

/** 例題の定義を、編集してよい新しいオブジェクトとして返す */
export function clonePreset(id) {
  const p = PRESETS.find((x) => x.id === id) ?? PRESETS[0];
  return {
    blank: p.blank,
    tape: p.tape,
    head: p.head,
    start: p.start,
    halt: [...p.halt],
    rules: p.rules.map((r) => ({ ...r })),
    layout: cloneLayout(p.layout),
  };
}

/** 状態遷移図の配置 { 状態名: [x, y] } の複製 */
export function cloneLayout(layout) {
  return Object.fromEntries(Object.entries(layout ?? {}).map(([k, v]) => [k, [...v]]));
}
